#!/usr/bin/env python3
"""把 web/index.html + app.css + app.js 合并为单一内联 HTML，输出 C 头文件。

用法:
  python3 scripts/inline_static.py --web-dir main/web --output build/main/web_index_html.h

输入：
  main/web/index.html  - 含 <!-- INLINE_CSS --> 与 <!-- INLINE_JS --> 占位符
  main/web/app.css     - 全部 CSS
  main/web/app.js      - 全部 JS

输出（C 头文件）:
  static const char index_html[] = "...";     // 内联完整 HTML
  static const unsigned int index_html_len = ...;

iOS Captive Portal WebView 不能加载外部 .css/.js，必须内联。
"""
import argparse
import os
import re
import sys

CSS_PLACEHOLDER = "<!-- INLINE_CSS -->"
JS_PLACEHOLDER = "<!-- INLINE_JS -->"


def read_text(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def c_string_literal(content, width=160):
    """把任意文本转换为 C 字符串字面量（按固定宽度切片拼接）。"""
    escaped = (content
               .replace("\\", "\\\\")
               .replace('"', '\\"')
               .replace("\r", "\\r")
               .replace("\n", "\\n"))
    lines = []
    i = 0
    while i < len(escaped):
        end = min(i + width, len(escaped))
        if end < len(escaped) and escaped[end - 1] == "\\":
            end -= 1
        lines.append('    "' + escaped[i:end] + '"')
        i = end
    return "\n".join(lines)


def minify_css(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    css = re.sub(r"\s+", " ", css)
    css = re.sub(r"\s*([{}:;,>])\s*", r"\1", css)
    css = css.replace(";}", "}")
    return css.strip()


def _strip_js_line_comment(line):
    out = []
    quote = ""
    escaped = False
    i = 0
    while i < len(line):
        ch = line[i]
        nxt = line[i + 1] if i + 1 < len(line) else ""
        if quote:
            out.append(ch)
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == quote:
                quote = ""
            i += 1
            continue
        if ch in ("'", '"', "`"):
            quote = ch
            out.append(ch)
            i += 1
            continue
        if ch == "/" and nxt == "/":
            break
        out.append(ch)
        i += 1
    return "".join(out)


def minify_js(js):
    js = re.sub(r"/\*.*?\*/", "", js, flags=re.S)
    lines = []
    for line in js.splitlines():
        stripped = _strip_js_line_comment(line).strip()
        if stripped:
            lines.append(stripped)
    return " ".join(lines)


def minify_html(html):
    html = re.sub(r"<!--(?! INLINE_(?:CSS|JS) ).*?-->", "", html, flags=re.S)
    html = re.sub(r">\s+<", "><", html)
    html = re.sub(r"\s+", " ", html)
    return html.strip()


def inline_html(html, css, js):
    """把 CSS/JS 内联进 HTML 占位符位置。"""
    if CSS_PLACEHOLDER not in html:
        raise SystemExit("index.html 缺少 " + CSS_PLACEHOLDER)
    if JS_PLACEHOLDER not in html:
        raise SystemExit("index.html 缺少 " + JS_PLACEHOLDER)
    html = html.replace(CSS_PLACEHOLDER, "<style>\n" + css + "\n</style>")
    html = html.replace(JS_PLACEHOLDER, "<script>\n" + js + "\n</script>")
    return html


def main():
    ap = argparse.ArgumentParser(description="内联 web 静态资源为 C 头文件")
    ap.add_argument("--web-dir", required=True, help="web 资源目录")
    ap.add_argument("--output", required=True, help="输出 .h 文件路径")
    ap.add_argument("--no-minify", action="store_true", help="不压缩内联资源，便于定位前端问题")
    ap.add_argument("--report", action="store_true", help="输出内联资源压缩前后体积")
    args = ap.parse_args()

    html_path = os.path.join(args.web_dir, "index.html")
    css_path = os.path.join(args.web_dir, "app.css")
    js_path = os.path.join(args.web_dir, "app.js")

    for p in [html_path, css_path, js_path]:
        if not os.path.isfile(p):
            print("FAIL: 缺少文件 " + p, file=sys.stderr)
            return 1

    html = read_text(html_path)
    css = read_text(css_path)
    js = read_text(js_path)

    raw_merged = inline_html(html, css, js)
    if args.no_minify:
        merged = raw_merged
    else:
        merged = inline_html(minify_html(html), minify_css(css), minify_js(js))

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as f:
        f.write("/* AUTO-GENERATED by scripts/inline_static.py - DO NOT EDIT */\n")
        f.write("#pragma once\n\n")
        f.write("static const char index_html[] =\n")
        f.write(c_string_literal(merged))
        f.write("    ;\n\n")
        f.write("static const unsigned int index_html_len = sizeof(index_html) - 1;\n")

    bytes_saved = len(raw_merged.encode("utf-8")) - len(merged.encode("utf-8"))
    print("OK: 生成 " + args.output + " (" + str(len(merged.encode("utf-8"))) + " bytes)")
    if args.report:
        print("web inline report: raw_bytes=" + str(len(raw_merged.encode("utf-8")))
              + " output_bytes=" + str(len(merged.encode("utf-8")))
              + " bytes_saved=" + str(bytes_saved))
    return 0


if __name__ == "__main__":
    sys.exit(main())
